/* ================= HELPER FUNCTIONS ================= */

/**
 * Determine threat type from login log data
 */
function determineThreatType(log) {
  const threats = [];

  if (log.keystrokeAnalysis?.anomalyScore > 40) {
    threats.push("Behavioral Anomaly");
  }
  if (log.travelAnalysis?.impossibleTravel) {
    threats.push("Impossible Travel");
  }
  if (log.riskScore >= 80) {
    threats.push("Account Takeover Attempt");
  }
  if (log.status === "blocked") {
    threats.push("Blocked Login");
  }
  if (log.riskComponents?.deviceRisk?.isNewDevice) {
    threats.push("New Device Login");
  }
  if (log.temporalAnalysis?.isUnusualTime) {
    threats.push("Unusual Login Time");
  }

  return threats.length > 0 ? threats.join(", ") : "Suspicious Activity";
}

/**
 * Generate notes from login log analysis
 */
function generateNotes(log) {
  const notes = [];

  notes.push(`Risk Score: ${log.riskScore}/100 (${log.riskLevel} Risk)`);
  notes.push(`IP: ${log.ipAddress}`);
  notes.push(`Location: ${log.state || 'Unknown'}, ${log.country || 'Unknown'}`);
  notes.push(`Device: ${log.device} (${log.browser} on ${log.os})`);

  if (log.keystrokeAnalysis?.anomalyScore > 40) {
    notes.push(`Behavioral Anomaly: ${log.keystrokeAnalysis.anomalyScore}% deviation`);
  }

  if (log.travelAnalysis?.impossibleTravel) {
    notes.push(`Impossible Travel: ${log.travelAnalysis.distanceTraveled}km in ${log.travelAnalysis.timeSinceLastLogin}h`);
  }

  if (log.threatExplanation?.reasons?.length > 0) {
    notes.push(`Reasons: ${log.threatExplanation.reasons.join('; ')}`);
  }

  return notes.join('\n');
}

