/* ================= UPDATE CASE ================= */
router.put("/:id", async (req, res) => {
  try {
    const { actionTaken, threatType, notes, status, severity, assignedTo } = req.body;

    const updatedCase = await Case.findByIdAndUpdate(
      req.params.id,
      {
        $set: {
          ...(actionTaken && { actionTaken }),
          ...(threatType && { threatType }),
          ...(notes && { notes }),
          ...(status && { status }),
          ...(severity && { severity }),
          ...(assignedTo && { assignedTo }),
          updatedAt: new Date()
        }
      },
      { new: true }
    );

    if (!updatedCase) {
      return res.status(404).json({ message: "Case not found" });
    }

    // If resolved, mark the related login log
    if (status === "Resolved") {
      await LoginLog.findByIdAndUpdate(updatedCase.loginLogId, {
        resolved: true
      });
    }

    res.json({
      success: true,
      message: "Case updated successfully",
      case: updatedCase
    });

  } catch (error) {
    console.error("Update case error:", error);
    res.status(500).json({ message: "Server error" });
  }
});

/* ================= DELETE CASE ================= */
router.delete("/:id", async (req, res) => {
  try {
    const deletedCase = await Case.findByIdAndDelete(req.params.id);
    if (!deletedCase) {
      return res.status(404).json({ message: "Case not found" });
    }

    // Unmark the login log
    if (deletedCase.loginLogId) {
      await LoginLog.findByIdAndUpdate(deletedCase.loginLogId, {
        isReported: false,
        resolved: false
      });
    }

    res.json({ success: true, message: "Case deleted" });
  } catch (error) {
    console.error("Delete case error:", error);
    res.status(500).json({ message: "Server error" });
  }
});

