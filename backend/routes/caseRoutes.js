const express = require("express");
const router = express.Router();
const Case = require("../models/Case");
const LoginLog = require("../models/LoginLog");
const User = require("../models/User");

/* ================= CREATE CASE FROM LOGIN LOG ================= */
router.post("/create", async (req, res) => {
  try {
    const { logId, actionTaken, threatType, notes, severity } = req.body;

    // Find the login log
    const log = await LoginLog.findById(logId);
    if (!log) {
      return res.status(404).json({ message: "Login log not found" });
    }

    // Check if case already exists for this log
    const existingCase = await Case.findOne({ loginLogId: logId });
    if (existingCase) {
      return res.status(400).json({ 
        message: "Case already exists for this log",
        case: existingCase
      });
    }

    // Create new case
    const newCase = new Case({
      email: log.email,
      userId: log.userId,
      loginLogId: log._id,
      status: "Open",
      severity: severity || "Medium",
      actionTaken: actionTaken || "Investigation Pending",
      threatType: threatType || determineThreatType(log),
      notes: notes || generateNotes(log),
      ipAddress: log.ipAddress,
      deviceId: log.deviceId,
      country: log.country,
      riskScore: log.riskScore,
      riskLevel: log.riskLevel,
      loginTimestamp: log.createdAt
    });

    await newCase.save();

    // Update the login log to mark as reported
    log.isReported = true;
    log.resolved = false;
    await log.save();

    // Emit real-time alert
    const io = req.app.get("io");
    if (io) {
      io.to("role:admin").emit("case:created", {
        caseId: newCase._id,
        email: newCase.email,
        threatType: newCase.threatType,
        riskScore: newCase.riskScore
      });
    }

    res.status(201).json({
      success: true,
      message: "Case created successfully",
      case: newCase
    });

  } catch (error) {
    console.error("Case creation error:", error);
    res.status(500).json({ message: "Server error" });
  }
});

/* ================= AUTO-CREATE CASE FROM HIGH RISK LOGIN ================= */
router.post("/auto-create", async (req, res) => {
  try {
    const { logId } = req.body;

    const log = await LoginLog.findById(logId);
    if (!log) {
      return res.status(404).json({ message: "Login log not found" });
    }

    // Only auto-create for high risk
    if (log.riskScore < 60) {
      return res.status(400).json({ 
        message: "Risk score too low for automatic case creation" 
      });
    }

    const existingCase = await Case.findOne({ loginLogId: logId });
    if (existingCase) {
      return res.json({ 
        success: true, 
        message: "Case already exists",
        case: existingCase 
      });
    }

    const newCase = new Case({
      email: log.email,
      userId: log.userId,
      loginLogId: log._id,
      status: "Open",
      severity: log.riskScore >= 80 ? "Critical" : log.riskScore >= 60 ? "High" : "Medium",
      actionTaken: "Automatic Detection - Investigation Required",
      threatType: determineThreatType(log),
      notes: generateNotes(log),
      ipAddress: log.ipAddress,
      deviceId: log.deviceId,
      country: log.country,
      riskScore: log.riskScore,
      riskLevel: log.riskLevel,
      loginTimestamp: log.createdAt,
      autoGenerated: true
    });

    await newCase.save();

    log.isReported = true;
    await log.save();

    const io = req.app.get("io");
    if (io) {
      io.to("role:admin").emit("case:auto-created", {
        caseId: newCase._id,
        email: newCase.email,
        threatType: newCase.threatType,
        riskScore: newCase.riskScore
      });
    }

    res.status(201).json({
      success: true,
      message: "Case auto-created from high-risk login",
      case: newCase
    });

  } catch (error) {
    console.error("Auto case creation error:", error);
    res.status(500).json({ message: "Server error" });
  }
});

/* ================= GET ALL CASES ================= */
router.get("/", async (req, res) => {
  try {
    const { status, severity, email } = req.query;
    
    let query = {};
    if (status) query.status = status;
    if (severity) query.severity = severity;
    if (email) query.email = email;

    const cases = await Case.find(query)
      .sort({ createdAt: -1 })
      .limit(100);

    res.json(cases);
  } catch (error) {
    console.error("Fetch cases error:", error);
    res.status(500).json({ message: "Server error" });
  }
});

